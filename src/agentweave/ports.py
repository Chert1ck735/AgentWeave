    async def pending_runtime_count(self, agent_id: str) -> int: ...
    async def recoverable_page(self, agent_id: str, *, after_task_id: str | None = None, limit: int = 64) -> list[TaskRecord]: ...
    async def append_progress(self, task_id: str, envelope: Envelope) -> int: ...
